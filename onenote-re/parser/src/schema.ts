export const Prop: Record<string, number> = Object.fromEntries(PROPS.map(([n, v]) => [n, v & 0x3ffffff]));
export const PROP_NAMES = new Map<number, string>(PROPS.map(([n, v]) => [v & 0x3ffffff, n]));

export function propName(id: number): string {
  return PROP_NAMES.get(id) ?? `0x${id.toString(16)}`;
}

export function jcidName(raw: number): string {
  return JCID_NAMES.get(raw) ?? `jcid_0x${raw.toString(16)}`;
}
